"""
PRISM Models — Temporal Transformer Dataset

PyTorch Dataset and DataLoader factory for 30-day cough trajectory sequences.

Reads CSV files generated by ``generate_temporal_data.py`` and returns
(sequence, label) pairs suitable for the TemporalTransformer model.

Usage::

    from models.temporal_transformer.dataset import create_temporal_dataloaders

    loaders = create_temporal_dataloaders(data_dir="datasets/temporal")
    for seq, label in loaders["train"]:
        # seq.shape  = (B, 30, 5)
        # label.shape = (B,)
        ...
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
import torch
from torch.utils.data import DataLoader, Dataset

# The 5 input features in column order
FEATURE_COLUMNS = [
    "cough_count",
    "avg_duration",
    "avg_intensity",
    "night_ratio",
    "inter_cough_interval",
]

SEQUENCE_LENGTH = 30


class TemporalDataset(Dataset):
    """
    PyTorch Dataset for temporal trajectory classification.

    Each item is a tuple of:
        sequence: FloatTensor shape (seq_len, 5) — daily cough features
        label: int — trajectory class (0–3)

    The dataset reads a CSV where each row is one day for one patient,
    groups by patient_id, and returns the full 30-day sequence.
    """

    def __init__(
        self,
        csv_path: str | Path,
        normalize: bool = True,
        feature_stats: dict[str, tuple[float, float]] | None = None,
    ) -> None:
        """
        Args:
            csv_path: path to the temporal CSV file
            normalize: whether to z-score normalize features
            feature_stats: pre-computed (mean, std) per feature column.
                           If None and normalize=True, computes from this file.
        """
        self.df = pd.read_csv(csv_path)
        self.normalize = normalize

        # Group by patient
        self.patients = sorted(self.df["patient_id"].unique())
        self.patient_data: dict[int, tuple[np.ndarray, int]] = {}

        for pid in self.patients:
            patient_df = self.df[self.df["patient_id"] == pid].sort_values("day")
            features = patient_df[FEATURE_COLUMNS].values.astype(np.float32)
            label = int(patient_df["trajectory_label"].iloc[0])
            self.patient_data[pid] = (features, label)

        # Compute or receive normalisation stats
        if normalize:
            if feature_stats is not None:
                self.feature_stats = feature_stats
            else:
                self.feature_stats = self._compute_stats()
        else:
            self.feature_stats = {}

    def _compute_stats(self) -> dict[str, tuple[float, float]]:
        """Compute per-feature mean and std from all data."""
        stats = {}
        for col in FEATURE_COLUMNS:
            mean = float(self.df[col].mean())
            std = float(self.df[col].std())
            stats[col] = (mean, max(std, 1e-6))
        return stats

    def get_feature_stats(self) -> dict[str, tuple[float, float]]:
        """Return the feature normalisation stats (useful for passing to val/test)."""
        return self.feature_stats

    def __len__(self) -> int:
        return len(self.patients)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        pid = self.patients[idx]
        features, label = self.patient_data[pid]

        # Convert to tensor
        seq = torch.from_numpy(features.copy())  # (seq_len, 5)

        # Normalize using z-score
        if self.normalize and self.feature_stats:
            for i, col in enumerate(FEATURE_COLUMNS):
                mean, std = self.feature_stats[col]
                seq[:, i] = (seq[:, i] - mean) / std

        return seq, label


def create_temporal_dataloaders(
    data_dir: str | Path = "datasets/temporal",
    batch_size: int = 16,
    num_workers: int = 0,
    pin_memory: bool = True,
    normalize: bool = True,
) -> dict[str, DataLoader]:
    """
    Create train/val/test DataLoaders for temporal trajectory data.

    Normalisation stats are computed from the training set and applied
    to val/test sets for consistency.

    Args:
        data_dir: directory containing temporal_train.csv, temporal_val.csv,
                  temporal_test.csv
        batch_size: batch size for all loaders
        num_workers: DataLoader worker count
        pin_memory: pin memory for GPU transfer
        normalize: whether to z-score normalize features

    Returns:
        Dict with keys "train", "val", "test" → DataLoader.
    """
    data_dir = Path(data_dir)

    # Build training dataset first (to get normalisation stats)
    train_dataset = TemporalDataset(
        csv_path=data_dir / "temporal_train.csv",
        normalize=normalize,
    )
    train_stats = train_dataset.get_feature_stats() if normalize else None

    # Val and test use training stats for normalisation
    val_dataset = TemporalDataset(
        csv_path=data_dir / "temporal_val.csv",
        normalize=normalize,
        feature_stats=train_stats,
    )
    test_dataset = TemporalDataset(
        csv_path=data_dir / "temporal_test.csv",
        normalize=normalize,
        feature_stats=train_stats,
    )

    loaders: dict[str, DataLoader] = {}

    for split_name, dataset, shuffle in [
        ("train", train_dataset, True),
        ("val", val_dataset, False),
        ("test", test_dataset, False),
    ]:
        loaders[split_name] = DataLoader(
            dataset,
            batch_size=batch_size,
            shuffle=shuffle,
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=(split_name == "train"),
        )

    return loaders
